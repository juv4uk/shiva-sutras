#!/usr/bin/env python3
"""Emit tables.h for bench7.c from the REAL prototypes (survey_7bit.py) and the UPC-14 graph oracle.

Index i = the position of a sound in upc14v2.SOUNDS (42 sounds). For each design the cell of every sound, the
graph's savarna (1.1.9) as the oracle, and the pratyahara sets ac and jhal.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import oracle_io  # noqa: E402
import survey_7bit as s  # noqa: E402
import upc14v2 as g  # noqa: E402

SOUNDS = list(g.SOUNDS)
DESIGNS = [("H", s.cells_hand), ("D", s.cells_derived), ("V", s.cells_varna),
           ("A", s.cells_akshara), ("T", s.cells_tantu), ("L", s.cells_legacy)]


def main() -> None:
    out = ["/* generated by gen_tables.py from the real prototypes: do not edit */", "#include <stdint.h>",
           f"#define NSOUNDS {len(SOUNDS)}"]
    for key, build in DESIGNS:
        cells = build()
        out.append(f"static const uint8_t CELL_{key}[NSOUNDS] = {{" + ",".join(str(cells[n]) for n in SOUNDS) + "};")
    rows = []
    for a in SOUNDS:
        bits = sum(1 << j for j, b in enumerate(SOUNDS) if g.savarna(g.SOUNDS[a], g.SOUNDS[b]))
        rows.append(f"0x{bits:x}ULL")
    out.append("static const uint64_t ORACLE_SAVARNA[NSOUNDS] = {" + ",".join(rows) + "};   /* bit j of row i: savarna(i, j) */")
    sets = {n: frozenset(names) for n, names in s.pratyahara_sets()}
    for label, name in (("AC", "ac"), ("JHAL", "jhal")):
        mask = sum(1 << i for i, n in enumerate(SOUNDS) if n in sets[name])
        out.append(f"static const uint64_t ORACLE_{label} = 0x{mask:x}ULL;   /* bit i: sound i is in {name} */")
    for key, build in DESIGNS:
        cells = build()
        ac = sorted(cells[n] for n in SOUNDS if n in sets["ac"])
        out.append(f"static const int AC_LO_{key} = {ac[0]}, AC_HI_{key} = {ac[-1]}, AC_CONTIGUOUS_{key} = {int(ac[-1]-ac[0]+1==len(ac))};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
