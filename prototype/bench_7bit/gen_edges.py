#!/usr/bin/env python3
"""Emit edges.h for bench_edges.c: the edge pairs of the 46 sounds that have a hand-table cell, as 14-bit codes (A) and hand cells (B, C).

Domain of an edge: every pair (c, r) with c a sound of the 46 (42 + ā ī ū ṝ), r = the graph edge of c, r also one of the 46 and r != c.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import survey_7bit as s  # noqa: E402
import upc14v2 as g  # noqa: E402
import upc14v2_sandhi as sd  # noqa: E402

NAMES = list(g.SOUNDS) + ["ā", "ī", "ū", "ṝ"]
EDGES = [("asp", g.e_asp), ("voice", g.e_voice), ("nasal", g.e_nasal), ("shift", g.e_shift), ("long", g.e_long)]


def pairs(edge):
    hand = s.cells_hand()
    code = {n: sd.code_of(n) for n in NAMES}
    name_of = {c: n for n, c in code.items()}
    out = []
    for n in NAMES:
        try:
            r = edge(code[n])
        except g.GraphError:
            continue
        if r in name_of and r != code[n]:
            out.append((code[n], r, hand[n], hand[name_of[r]]))
    return out


def main() -> None:
    out = ["/* generated by gen_edges.py: do not edit */", "#include <stdint.h>"]
    for name, edge in EDGES:
        ps = pairs(edge)
        out.append(f"#define N_{name.upper()} {len(ps)}")
        for label, idx in (("IN14", 0), ("OUT14", 1)):
            out.append(f"static const uint16_t {label}_{name.upper()}[N_{name.upper()}] = {{" + ",".join(str(p[idx]) for p in ps) + "};")
        for label, idx in (("INH", 2), ("OUTH", 3)):
            out.append(f"static const uint8_t {label}_{name.upper()}[N_{name.upper()}] = {{" + ",".join(str(p[idx]) for p in ps) + "};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
